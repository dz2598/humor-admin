do $$
declare table_name text;
begin
  foreach table_name in array array[
    'prompt_chains','prompt_chain_steps','prompt_chain_mix','terms','generation_requests',
    'llm_providers','llm_models','llm_responses','ai_generation_examples',
    'allowed_signup_domains','whitelisted_emails'
  ] loop
    execute format('drop policy if exists "Superadmins manage %s" on public.%I', table_name, table_name);
    execute format(
      'create policy "Superadmins manage %s" on public.%I for all to authenticated using (public.is_superadmin()) with check (public.is_superadmin())',
      table_name, table_name
    );
  end loop;
end $$;

-- The user-facing generator may read active configuration and log its own requests.
drop policy if exists "Authenticated users read generation configuration" on public.prompt_chains;
create policy "Authenticated users read generation configuration" on public.prompt_chains for select to authenticated using (true);
drop policy if exists "Authenticated users read prompt mix" on public.prompt_chain_mix;
create policy "Authenticated users read prompt mix" on public.prompt_chain_mix for select to authenticated using (true);
drop policy if exists "Authenticated users read models" on public.llm_models;
create policy "Authenticated users read models" on public.llm_models for select to authenticated using (true);

drop policy if exists "Users insert own generation requests" on public.generation_requests;
create policy "Users insert own generation requests" on public.generation_requests for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "Users update own generation requests" on public.generation_requests;
create policy "Users update own generation requests" on public.generation_requests for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "Users read own generation requests" on public.generation_requests;
create policy "Users read own generation requests" on public.generation_requests for select to authenticated using (user_id = auth.uid());

drop policy if exists "Users insert responses for own requests" on public.llm_responses;
create policy "Users insert responses for own requests" on public.llm_responses for insert to authenticated with check (
  exists (select 1 from public.generation_requests request where request.id = generation_request_id and request.user_id = auth.uid())
);

-- Superadmins can upload, replace, and remove image objects from the existing public bucket.
drop policy if exists "Superadmins manage meme images" on storage.objects;
create policy "Superadmins manage meme images" on storage.objects for all to authenticated
using (bucket_id = 'memes' and public.is_superadmin())
with check (bucket_id = 'memes' and public.is_superadmin());

