create table if not exists public.prompt_chains (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  status text not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.prompt_chain_steps (
  id bigint generated by default as identity primary key,
  prompt_chain_id bigint not null references public.prompt_chains(id) on delete cascade,
  step_order integer not null default 1,
  name text not null,
  system_prompt text,
  user_prompt_template text,
  created_at timestamptz not null default now(),
  unique(prompt_chain_id, step_order)
);

create table if not exists public.prompt_chain_mix (
  id bigint generated by default as identity primary key,
  prompt_chain_id bigint not null unique references public.prompt_chains(id) on delete cascade,
  weight numeric(5,2) not null default 100 check (weight >= 0 and weight <= 100),
  enabled boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.terms (
  id bigint generated by default as identity primary key,
  term text not null unique,
  definition text not null,
  category text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.generation_requests (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  prompt_chain_id bigint references public.prompt_chains(id) on delete set null,
  input_prompt text not null,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.llm_providers (
  id bigint generated by default as identity primary key,
  name text not null unique,
  api_base_url text,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.llm_models (
  id bigint generated by default as identity primary key,
  provider_id bigint not null references public.llm_providers(id) on delete cascade,
  name text not null,
  model_key text not null,
  context_window integer,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(provider_id, model_key)
);

create table if not exists public.llm_responses (
  id bigint generated by default as identity primary key,
  generation_request_id bigint references public.generation_requests(id) on delete cascade,
  model_id bigint references public.llm_models(id) on delete set null,
  response_text text,
  latency_ms integer,
  input_tokens integer,
  output_tokens integer,
  created_at timestamptz not null default now()
);

create table if not exists public.ai_generation_examples (
  id bigint generated by default as identity primary key,
  title text not null,
  prompt text not null,
  output_text text,
  image_url text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.allowed_signup_domains (
  id bigint generated by default as identity primary key,
  domain text not null unique,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.whitelisted_emails (
  id bigint generated by default as identity primary key,
  email text not null unique,
  notes text,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

